/**
 * プレートテクトニクス。docs/01-6.2 〜 6.5。
 *
 * 設計上の要点:
 *
 * 1. **プレートは回転する球面ボロノイで定義する。**
 *    各プレートは「種点」とオイラーベクトルを持ち、種点自身が回転する。
 *    セルの所属は最も近い種点で決まるので、境界が滑らかに動く。
 *    地殻パーセル（粒子）方式より実装が単純で、格子が破綻しない。
 *
 * 2. **剛体回転は球面上で発散ゼロ。**
 *    したがって速度の発散が非ゼロになるのは【プレート境界だけ】。
 *    境界の検出に特別な処理が要らない。div > 0 で発散境界、div < 0 で収束境界。
 *
 * 3. **地殻は「厚さ」の場として持ち、標高はアイソスタシーで導く。**
 *    大陸地殻の厚さ -> Airy アイソスタシー、海洋地殻 -> 年齢-深度関係。
 *    衝突で厚さが足し合わされるので、造山が自然に出る。
 */

